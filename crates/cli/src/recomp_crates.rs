//! The Cargo side of recompiled builds (docs/recompiler.md): each recompiled
//! program is a crate of its own under out/recomp/, and a generated
//! workspace builds the front ends with a registry of them patched in for
//! the `remodel-recomp` stub. Separate crates compile (and are cached)
//! separately, so a build's peak memory is one program's, not all of them.

use std::fmt::Write as _;
use std::path::{Component, Path, PathBuf};

/// Where `remodel recomp` puts the programs and the native workspace.
pub const DIR: &str = "out/recomp";

/// What the workspace builds.
pub enum Front {
    /// The `remodel` and `remodel-play` binaries.
    Native,
    /// The browser module (`remodel-web`).
    Web,
}

/// Write `contents` to `path` unless it already holds exactly that, so
/// Cargo sees nothing new and keeps what it built from it.
fn write_if_changed(path: &Path, contents: &str) -> Result<(), String> {
    if std::fs::read_to_string(path).is_ok_and(|s| s == contents) {
        return Ok(());
    }
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    }
    std::fs::write(path, contents).map_err(|e| format!("{}: {e}", path.display()))
}

fn canonical(p: &Path) -> Result<PathBuf, String> {
    p.canonicalize().map_err(|e| format!("{}: {e}", p.display()))
}

/// `to` relative to the directory `from` (both absolute), with `/`.
fn relative(from: &Path, to: &Path) -> String {
    let (f, t): (Vec<Component>, Vec<Component>) = (from.components().collect(), to.components().collect());
    let common = f.iter().zip(&t).take_while(|(a, b)| a == b).count();
    let mut parts: Vec<String> = vec!["..".into(); f.len() - common];
    parts.extend(t[common..].iter().map(|c| c.as_os_str().to_string_lossy().into_owned()));
    if parts.is_empty() {
        ".".into()
    } else {
        parts.join("/")
    }
}

/// The reModel checkout: the current directory, as `make` runs from it.
fn repo() -> Result<PathBuf, String> {
    let dir = canonical(Path::new("."))?;
    if !dir.join("crates/model2/Cargo.toml").is_file() || !dir.join("crates/recomp/Cargo.toml").is_file() {
        return Err(format!("{}: not the reModel checkout (run this from its root)", dir.display()));
    }
    Ok(dir)
}

/// `i960_<hash>` / `tgp_<hash>` / `sharc_<hash>`: a program crate's
/// directory name.
fn is_program(name: &str) -> bool {
    let hash = name.strip_prefix("i960_").or_else(|| name.strip_prefix("tgp_")).or_else(|| name.strip_prefix("sharc_"));
    hash.is_some_and(|h| h.len() == 16 && h.bytes().all(|b| b.is_ascii_hexdigit()))
}

/// Write a program's crate, `dir/<name>/`, around `code` from
/// `i960::codegen`, `mb86235::codegen` or `adsp2106x::codegen`; `name` is
/// `i960_<hash>`, `tgp_<hash>` or `sharc_<hash>`. Files that haven't changed are left alone.
pub fn write_program(dir: &Path, name: &str, code: &str) -> Result<PathBuf, String> {
    let krate = dir.join(name);
    write_if_changed(&krate.join("program.rs"), code)?;
    write_glue(&krate, name)?;
    Ok(krate)
}

/// Note that a SHARC program crate runs on `role` (`copro` or `geo`):
/// its glue instantiates the program for the buses of the roles in its
/// `roles.txt`, so a program captured on one processor isn't compiled for
/// the other too.
pub fn add_role(dir: &Path, name: &str, role: &str) -> Result<(), String> {
    let path = dir.join(name).join("roles.txt");
    let mut roles = roles(&dir.join(name));
    roles.insert(role.to_string());
    let text: String = roles.iter().map(|r| format!("{r}\n")).collect();
    write_if_changed(&path, &text)
}

fn roles(krate: &Path) -> std::collections::BTreeSet<String> {
    let text = std::fs::read_to_string(krate.join("roles.txt")).unwrap_or_default();
    text.lines().map(str::trim).filter(|l| matches!(*l, "copro" | "geo")).map(String::from).collect()
}

/// The crate's Cargo.toml and lib.rs: the generic program instantiated for
/// the Model 2 board's types, so it is compiled here and not in model2.
fn write_glue(krate: &Path, name: &str) -> Result<(), String> {
    let repo = repo()?;
    let at = canonical(krate)?;
    let dep = |c: &str| relative(&at, &repo.join("crates").join(c));
    let toml = format!(
        "# Generated by `remodel recomp` from game code: never commit it.\n\
         [package]\nname = \"remodel-recomp-{}\"\nversion = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n\
         [lib]\nname = \"{name}\"\npath = \"lib.rs\"\n\n\
         [dependencies]\nadsp2106x = {{ path = \"{}\" }}\ni960 = {{ path = \"{}\" }}\nmb86235 = {{ path = \"{}\" }}\nremodel-model2 = {{ path = \"{}\" }}\n",
        name.replace('_', "-"),
        dep("adsp2106x"),
        dep("i960"),
        dep("mb86235"),
        dep("model2"),
    );
    let mut lib = format!(
        "//! Recompiled program {name}, generated by `remodel recomp` from game code:\n\
         //! never commit it. program.rs is generic over the machine around the\n\
         //! processor; this instantiates it for the Model 2 board.\n\n\
         #[allow(warnings, clippy::all)]\n#[path = \"program.rs\"]\nmod program;\n\npub use program::HASH;\n\n"
    );
    if name.starts_with("i960_") {
        lib.push_str("pub fn blocks() -> Vec<(u32, model2::Block)> {\n    program::blocks::<model2::Model2Bus>()\n}\n");
    } else if name.starts_with("sharc_") {
        // Each role's `run`, or None (the registry takes both).
        let roles = roles(krate);
        lib.push_str(
            "use adsp2106x::cpu::{Sharc, Step};\n#[allow(unused_imports)]\n\
             use model2::recomp::{SharcCoproBus, SharcCoproRun, SharcGeoBus, SharcGeoRun};\n\n\
             pub use program::{IMAGE, WORDS};\n\n",
        );
        for (role, bus, ty) in [("copro", "SharcCoproBus", "SharcCoproRun"), ("geo", "SharcGeoBus", "SharcGeoRun")] {
            if roles.contains(role) {
                let _ = write!(
                    lib,
                    "fn {role}_run(s: &mut Sharc, ext: &mut {bus}<'_>) -> Step {{\n    program::run(s, ext)\n}}\n\n\
                     pub const {}: Option<{ty}> = Some({role}_run);\n\n",
                    role.to_uppercase()
                );
            } else {
                let _ = write!(lib, "pub const {}: Option<{ty}> = None;\n\n", role.to_uppercase());
            }
        }
    } else {
        lib.push_str(
            "use mb86235::cpu::{Step, Tgp};\nuse model2::recomp::{GeoExt, TgpExt};\n\n\
             pub fn copro(t: &mut Tgp, ext: &mut TgpExt<'_>) -> Step {\n    program::step(t, ext)\n}\n\n\
             pub fn geo(t: &mut Tgp, ext: &mut GeoExt<'_>) -> Step {\n    program::step(t, ext)\n}\n",
        );
    }
    write_if_changed(&krate.join("Cargo.toml"), &toml)?;
    write_if_changed(&krate.join("lib.rs"), &lib)
}

/// The program crates in `dir`, sorted. Loose `i960_<hash>.rs` and
/// `tgp_<hash>.rs` files (the layout before program crates) are moved into
/// crates of their own.
pub fn programs(dir: &Path) -> Result<Vec<String>, String> {
    let mut names = Vec::new();
    for e in std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?.flatten() {
        let Ok(name) = e.file_name().into_string() else { continue };
        if let Some(stem) = name.strip_suffix(".rs").filter(|s| is_program(s)) {
            let krate = dir.join(stem);
            std::fs::create_dir_all(&krate).map_err(|e| format!("{}: {e}", krate.display()))?;
            std::fs::rename(e.path(), krate.join("program.rs")).map_err(|e| format!("{name}: {e}"))?;
            names.push(stem.to_string());
        } else if is_program(&name) && e.path().join("program.rs").is_file() {
            names.push(name);
        }
    }
    names.sort();
    names.dedup();
    Ok(names)
}

/// The root manifest's `[profile.*]` sections and workspace version, so
/// the generated workspace builds the same way.
fn root_manifest(repo: &Path) -> Result<(String, String), String> {
    let path = repo.join("Cargo.toml");
    let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let (mut profiles, mut version, mut section) = (String::new(), None, String::new());
    for line in text.lines() {
        if line.starts_with('[') {
            section = line.trim().to_string();
        }
        if section.starts_with("[profile.") {
            profiles.push_str(line);
            profiles.push('\n');
        }
        if section == "[workspace.package]" {
            if let Some(v) = line.strip_prefix("version = ") {
                version = Some(v.trim().trim_matches('"').to_string());
            }
        }
    }
    let version = version.ok_or_else(|| format!("{}: no [workspace.package] version", path.display()))?;
    Ok((profiles, version))
}

/// Write the workspace at `root` that builds `front` with the programs
/// `names` (crates in `programs_dir`) registered: `registry/` (the
/// `remodel-recomp` that replaces the stub), `front/` (which only pulls the
/// front end into the workspace), `Cargo.toml`, and the checkout's
/// `Cargo.lock`, so dependencies are the same versions.
pub fn write_workspace(root: &Path, programs_dir: &Path, names: &[String], front: Front) -> Result<(), String> {
    let repo = repo()?;
    std::fs::create_dir_all(root).map_err(|e| format!("{}: {e}", root.display()))?;
    let root = canonical(root)?;
    let programs_dir = canonical(programs_dir)?;
    for n in names {
        write_glue(&programs_dir.join(n), n)?;
    }
    let (profiles, version) = root_manifest(&repo)?;
    let crates = |c: &str| relative(&root.join("x"), &repo.join("crates").join(c));

    // The registry: depends on every program and lists them for model2.
    let mut toml = format!(
        "# Generated by `remodel recomp`: never commit it.\n\
         [package]\nname = \"remodel-recomp\"\nversion = \"{version}\"\nedition = \"2021\"\npublish = false\n\n\
         [lib]\nname = \"recomp\"\npath = \"lib.rs\"\n\n\
         [dependencies]\nremodel-model2 = {{ path = \"{}\" }}\n",
        crates("model2")
    );
    let mut i960 = String::new();
    let mut tgp = String::new();
    let mut sharc = String::new();
    for n in names {
        let _ = writeln!(
            toml,
            "{n} = {{ package = \"remodel-recomp-{}\", path = \"{}\" }}",
            n.replace('_', "-"),
            relative(&root.join("registry"), &programs_dir.join(n))
        );
        if n.starts_with("i960_") {
            let _ = writeln!(i960, "    I960Program {{ hash: {n}::HASH, blocks: {n}::blocks }},");
        } else if n.starts_with("sharc_") {
            let _ = writeln!(
                sharc,
                "    SharcProgram {{ hash: {n}::HASH, image: {n}::IMAGE, words: {n}::WORDS, copro: {n}::COPRO, geo: {n}::GEO }},"
            );
        } else {
            let _ = writeln!(tgp, "    TgpProgram {{ hash: {n}::HASH, copro: {n}::copro, geo: {n}::geo }},");
        }
    }
    let lib = format!(
        "//! Every recompiled program in this build, generated by `remodel recomp`.\n\n\
         use model2::recomp::{{I960Program, Programs, SharcProgram, TgpProgram}};\n\n\
         static I960: &[I960Program] = &[\n{i960}];\n\n\
         static TGP: &[TgpProgram] = &[\n{tgp}];\n\n\
         static SHARC: &[SharcProgram] = &[\n{sharc}];\n\n\
         /// Hand this build's recompiled programs to model2.\n\
         pub fn register() {{\n    model2::recomp::register(Programs {{ i960: I960, tgp: TGP, sharc: SHARC }});\n}}\n"
    );
    write_if_changed(&root.join("registry/Cargo.toml"), &toml)?;
    write_if_changed(&root.join("registry/lib.rs"), &lib)?;

    // `cargo build -p` only builds packages in the workspace's dependency
    // graph, and the front ends can't be members (they belong to the
    // checkout's workspace), so this crate depends on them. Cargo warns that
    // it ignores a dependency without a library, and does: nothing is linked
    // here. (A dependency under a `cfg` that never holds, which would stay
    // quiet, makes Cargo 1.99's feature resolver panic.)
    let fronts: &[(&str, &str)] = match front {
        Front::Native => &[("remodel", "cli"), ("remodel-play", "play")],
        Front::Web => &[("remodel-web", "web")],
    };
    let mut toml = String::from(
        "# Generated by `remodel recomp`: never commit it.\n\
         [package]\nname = \"remodel-recomp-front\"\nversion = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n\
         [lib]\npath = \"lib.rs\"\n\n[dependencies]\n",
    );
    for (package, dir) in fronts {
        let _ = writeln!(toml, "{package} = {{ path = \"{}\" }}", crates(dir));
    }
    write_if_changed(&root.join("front/Cargo.toml"), &toml)?;
    write_if_changed(&root.join("front/lib.rs"), "//! Empty: see Cargo.toml.\n")?;

    let stub = repo.join("crates/recomp");
    let toml = format!(
        "# Generated by `remodel recomp`: never commit it. Builds the front ends with\n\
         # registry/ in place of the `remodel-recomp` stub (docs/recompiler.md).\n\
         [workspace]\nresolver = \"2\"\nmembers = [\"registry\", \"front\"]\n\n\
         [patch.\"file://{}\"]\nremodel-recomp = {{ path = \"registry\" }}\n\n{profiles}",
        stub.display()
    );
    write_if_changed(&root.join("Cargo.toml"), &toml)?;
    let lock = repo.join("Cargo.lock");
    let lock = std::fs::read_to_string(&lock).map_err(|e| format!("{}: {e}", lock.display()))?;
    // Cargo adds the generated packages to it again; nothing is rebuilt.
    write_if_changed(&root.join("Cargo.lock"), &lock)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn relative_paths() {
        assert_eq!(relative(Path::new("/a/out/recomp/x"), Path::new("/a/crates/i960")), "../../../crates/i960");
        assert_eq!(relative(Path::new("/a/out/recomp/registry"), Path::new("/a/out/recomp/tgp_1")), "../tgp_1");
        assert_eq!(relative(Path::new("/a"), Path::new("/a")), ".");
    }

    #[test]
    fn program_names() {
        assert!(is_program("i960_0123456789abcdef"));
        assert!(is_program("tgp_0123456789abcdef"));
        assert!(is_program("sharc_0123456789abcdef"));
        assert!(!is_program("tgp_0123"));
        assert!(!is_program("registry"));
    }
}
